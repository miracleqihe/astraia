import { createHash } from 'node:crypto';
import { access, lstat, mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { shardKey } from '../src/syzygy/shardKey.js';

const webRoot = fileURLToPath(new URL('../', import.meta.url));
let defaultGraph = `${webRoot}/public/data/graph_data.json`;
if (process.env.VITE_PUBLIC_DEMO !== '1') {
  try { await access(`${webRoot}/public/data/catalogue_data.json`); defaultGraph = `${webRoot}/public/data/catalogue_data.json`; } catch { /* Public graph fallback. */ }
}
const graphPath = resolve(process.argv[2] ?? defaultGraph);
const out = resolve(process.argv[3] ?? `${webRoot}/public/syzygy/shards`);
const bookPath = resolve(process.argv[4] ?? `${webRoot}/public/knowledge/data.json`);
const [graphBytes, bookBytes] = await Promise.all([readFile(graphPath), readFile(bookPath)]);
const graph = JSON.parse(graphBytes.toString('utf8'));
const book = JSON.parse(bookBytes.toString('utf8'));
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const bookHash = digest(bookBytes);
if (graph.schema_version !== 1 || !/^[a-f0-9]{64}$/.test(graph.snapshot_id ?? '') || !Array.isArray(graph.nodes) || !Array.isArray(book.entries)) {
  throw new Error('Invalid graph or handbook: cannot build reading shards.');
}
const buckets = 64;
await mkdir(out, { recursive: true });
if ((await lstat(out)).isSymbolicLink()) throw new Error('The shard output directory must not be a symbolic link.');
// A private development catalogue must never be copied into a public build.
// Remove only files generated by this script before writing the selected snapshot.
for (const name of await readdir(out)) {
  if (/^(?:(?:graph|book)-[a-f0-9]{12}-\d{2}-[a-f0-9]{16}|manifest-[a-f0-9]{12}-[a-f0-9]{12})\.json$/.test(name)) {
    const path = `${out}/${name}`;
    if (!(await lstat(path)).isFile()) throw new Error(`Unexpected generated shard path: ${path}`);
    await unlink(path);
  }
}
async function save(name, bytes) {
  const path = `${out}/${name}`;
  let old;
  try { old = await readFile(path); } catch { /* First build. */ }
  if (!old?.equals(bytes)) await writeFile(path, bytes);
}
async function build(kind, records, source) {
  const groups = Array.from({ length: buckets }, () => []);
  const ids = new Set();
  for (const item of records) {
    if (typeof item.id !== 'string' || !item.id || ids.has(item.id)) throw new Error(`Invalid ${kind} id: ${item.id}`);
    ids.add(item.id); groups[shardKey(item.id, buckets)].push(item);
  }
  const parts = [];
  for (const [index, items] of groups.entries()) {
    // A graph snapshot changes on every catalogue update. Keep that identity in
    // the manifest rather than every bucket so unchanged text is reusable.
    const payload = kind === 'graph'
      ? { schema_version: 2, kind, bucket: index, records: items }
      : { schema_version: 1, kind, source, bucket: index, records: items };
    const bytes = Buffer.from(JSON.stringify(payload) + '\n', 'utf8');
    const sha256 = digest(bytes);
    const prefix = kind === 'graph' ? sha256.slice(0, 12) : source.slice(0, 12);
    const suffix = kind === 'graph' ? sha256.slice(12, 28) : sha256.slice(0, 16);
    const file = `${kind}-${prefix}-${index.toString().padStart(2, '0')}-${suffix}.json`;
    await save(file, bytes); parts.push({ file, sha256, count: items.length });
  }
  return { count: ids.size, parts };
}
const records = graph.nodes.map(({ id, sources, audit, markdown, source_path, reading }) =>
  ({ id, sources, audit, markdown, source_path, ...(reading ? { reading } : {}) }));
const manifest = { schema_version: 1, snapshot_id: graph.snapshot_id, handbook_sha256: bookHash, buckets,
  graph: await build('graph', records, graph.snapshot_id), book: await build('book', book.entries, bookHash) };
const manifestName = `manifest-${graph.snapshot_id.slice(0, 12)}-${bookHash.slice(0, 12)}.json`;
await save(manifestName, Buffer.from(JSON.stringify(manifest) + '\n', 'utf8'));
console.log(`Reading shards: ${manifest.graph.count} graph records and ${manifest.book.count} handbook entries in ${buckets * 2} buckets.`);
